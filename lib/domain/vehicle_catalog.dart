  /// Generates manufacture years from next year down to 1980.
  static List<String> get years {
    final currentYear = DateTime.now().year;
    return [for (int y = currentYear + 1; y >= 1980; y--) y.toString()];
  }

  /// Returns known models for a given make, or empty list if make is unknown.
  static List<String> modelsForMake(String? make) {
