import 'dart:async';

import 'package:autonect/firebase_options.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

/// Starts Firebase exactly once, however many features ask for it.
///
/// Push (started at boot, not awaited) and Google sign-in (started when the
/// user taps) both need Firebase running. Each calling initializeApp on its own
/// can race; they share this one Future instead.
///
/// Returns false, never throws, when Firebase cannot start (no
/// google-services.json in the build, unsupported platform). Callers treat that
/// as "feature unavailable", never as a crash.
Future<bool> ensureFirebaseStarted() => _started ??= _start();

Future<bool>? _started;

Future<bool> _start() async {
  try {
    // Explicit options (generated by FlutterFire for project autonect1), so iOS
    // needs no GoogleService-Info.plist. Regenerate with `flutterfire
    // configure` if the package name or bundle id changes.
    if (Firebase.apps.isEmpty) {
      await Firebase.initializeApp(
        options: DefaultFirebaseOptions.currentPlatform,
      );
    }
    return true;
  } catch (e, st) {
    debugPrint('Firebase did not start: $e\n$st');
    return false;
  }
}
