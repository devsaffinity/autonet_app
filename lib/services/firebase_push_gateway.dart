import 'dart:async';
import 'dart:convert';
import 'dart:ui' show Color;

import 'package:autonect/services/firebase_bootstrap.dart';
import 'package:autonect/services/push_gateway.dart';
import 'package:firebase_messaging/firebase_messaging.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter_local_notifications/flutter_local_notifications.dart';

/// The only file that imports Firebase or flutter_local_notifications.
///
/// getToken / onTokenRefresh / deleteToken are deprecated in firebase_messaging
/// 17 in favour of register() and a Firebase Installation ID. The backend sends
/// to classic FCM registration tokens (PUSH-NOTIFICATIONS.md), which are what
/// these return; switch only when the server does.
// ignore_for_file: deprecated_member_use
class FirebasePushGateway implements PushGateway {
  /// MUST match the channel id the server sends on. Android 8+ shows a push on
  /// an unknown channel silently, with no heads-up banner.
  static const String channelId = 'autonect_default';

  static const AndroidNotificationChannel _channel = AndroidNotificationChannel(
    channelId,
    'Autonect',
    description: 'Bookings, messages, orders and billing',
    importance: Importance.high,
  );

  final FlutterLocalNotificationsPlugin _local =
      FlutterLocalNotificationsPlugin();
  final StreamController<PushMessage> _opened =
      StreamController<PushMessage>.broadcast();

  Future<bool>? _init;
  bool _ready = false;
  int _nextId = 0;

  @override
  bool get isSupported =>
      !kIsWeb &&
      (defaultTargetPlatform == TargetPlatform.android ||
          defaultTargetPlatform == TargetPlatform.iOS);

  @override
  String get platform =>
      defaultTargetPlatform == TargetPlatform.iOS ? 'IOS' : 'ANDROID';

  @override
  Future<bool> init() => _init ??= _doInit();

  Future<bool> _doInit() async {
    if (!isSupported) return false;
    try {
      // Shared with Google sign-in, which also needs Firebase. A failure here
      // must leave the app fully usable, just without push.
      if (!await ensureFirebaseStarted()) return false;

      await _local.initialize(
        settings: const InitializationSettings(
          // A status-bar icon must be a single-colour silhouette; the coloured
          // launcher icon renders as a flat blob. ic_launcher_monochrome is the
          // white wrench on transparent, generated by flutter_launcher_icons.
          android: AndroidInitializationSettings('@drawable/ic_launcher_monochrome'),
        ),
        onDidReceiveNotificationResponse: (r) {
          final m = _fromPayload(r.payload);
          if (m != null) _opened.add(m);
        },
      );
      await _local
          .resolvePlatformSpecificImplementation<
            AndroidFlutterLocalNotificationsPlugin
          >()
          ?.createNotificationChannel(_channel);

      // iOS draws foreground pushes itself when told to; Android never does.
      await FirebaseMessaging.instance
          .setForegroundNotificationPresentationOptions(
            alert: true,
            badge: true,
            sound: true,
          );

      FirebaseMessaging.onMessageOpenedApp.listen(
        (m) => _opened.add(_fromRemote(m)),
      );
      _ready = true;
      return true;
    } catch (e, st) {
      debugPrint('Push disabled — Firebase did not start: $e\n$st');
      return false;
    }
  }

  @override
  Future<bool> requestPermission() async {
    if (!_ready) return false;
    try {
      final s = await FirebaseMessaging.instance.requestPermission();
      return s.authorizationStatus == AuthorizationStatus.authorized ||
          s.authorizationStatus == AuthorizationStatus.provisional;
    } catch (_) {
      return false;
    }
  }

  @override
  Future<String?> getToken() async {
    if (!_ready) return null;
    try {
      return await FirebaseMessaging.instance.getToken();
    } catch (_) {
      // iOS before the APNs token arrives, or no Play services.
      return null;
    }
  }

  @override
  Stream<String> get onTokenRefresh =>
      _ready ? FirebaseMessaging.instance.onTokenRefresh : const Stream.empty();

  @override
  Stream<PushMessage> get onForeground => _ready
      ? FirebaseMessaging.onMessage.map(_fromRemote)
      : const Stream.empty();

  @override
  Stream<PushMessage> get onOpened => _opened.stream;

  @override
  Future<PushMessage?> initialMessage() async {
    if (!_ready) return null;
    try {
      final m = await FirebaseMessaging.instance.getInitialMessage();
      if (m != null) return _fromRemote(m);
      // A foreground push drawn locally, then tapped after the process died.
      final launch = await _local.getNotificationAppLaunchDetails();
      if (launch?.didNotificationLaunchApp ?? false) {
        return _fromPayload(launch!.notificationResponse?.payload);
      }
    } catch (_) {}
    return null;
  }

  @override
  Future<void> showLocal(PushMessage message) async {
    if (!_ready || defaultTargetPlatform != TargetPlatform.android) return;
    await _local.show(
      id: _nextId++ & 0x7fffffff,
      title: message.title,
      body: message.body,
      notificationDetails: NotificationDetails(
        android: AndroidNotificationDetails(
          _channel.id,
          _channel.name,
          channelDescription: _channel.description,
          importance: Importance.high,
          priority: Priority.high,
          icon: '@drawable/ic_launcher_monochrome',
          color: const Color(0xFFD94D2F),
        ),
      ),
      payload: jsonEncode({
        ...message.data,
        'title': message.title,
        'body': message.body,
      }),
    );
  }

  @override
  Future<void> deleteToken() async {
    if (!_ready) return;
    try {
      await FirebaseMessaging.instance.deleteToken();
    } catch (_) {}
  }

  /// `data.title/body` are repeated by the server because Android drops the
  /// `notification` block in the foreground — so prefer them, fall back to it.
  static PushMessage _fromRemote(RemoteMessage m) {
    final data = <String, String>{
      for (final e in m.data.entries) e.key: '${e.value}',
    };
    return PushMessage(
      title: data['title'] ?? m.notification?.title ?? '',
      body: data['body'] ?? m.notification?.body ?? '',
      data: data,
    );
  }

  static PushMessage? _fromPayload(String? payload) {
    if (payload == null || payload.isEmpty) return null;
    try {
      final j = jsonDecode(payload);
      if (j is! Map) return null;
      final data = <String, String>{
        for (final e in j.entries) '${e.key}': '${e.value}',
      };
      return PushMessage(
        title: data['title'] ?? '',
        body: data['body'] ?? '',
        data: data,
      );
    } catch (_) {
      return null;
    }
  }
}
